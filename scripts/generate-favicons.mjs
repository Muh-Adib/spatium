/**
 * Generates every site icon from the SPATIUM "A" mark in public/brand/.
 *
 *   node scripts/generate-favicons.mjs
 *
 * Outputs:
 *   public/favicon.svg          square, adapts to light/dark browser chrome
 *   src/app/favicon.ico         16/32/48 px (PNG-in-ICO), served at /favicon.ico
 *   public/apple-touch-icon.png 180 px
 *   public/icon-192.png, icon-512.png (PWA; 512 is maskable-safe)
 *
 * Raster icons put the white mark on the brand's dark tile so they stay legible on any
 * background and at 16 px.
 */
import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const root = path.resolve(import.meta.dirname, '..')
const MARK = path.join(root, 'public/brand/mark-spatium.svg')
const MARK_ON_DARK = path.join(root, 'public/brand/mark-spatium-white.svg')
const TILE = '#03060d' // matches themeColor / manifest background_color

// --- SVG favicon -----------------------------------------------------------
// The mark is 584.68 × 364.19; a square viewBox keeps it from shrinking in tab slots.
const mark = fs.readFileSync(MARK, 'utf8')
const gradient = mark.match(/<radialGradient[\s\S]*?<\/radialGradient>/)?.[0]
const paths = [...mark.matchAll(/<path\b[^>]*\/>/g)].map((m) => m[0])
if (!gradient || paths.length !== 2) throw new Error('Unexpected structure in public/brand/mark-spatium.svg')
const [accentPath, basePath] = paths
const W = 584.68
const H = 364.19
const PAD = 16
const side = W + PAD * 2
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-PAD} ${-(side - H) / 2} ${side} ${side}" role="img" aria-label="SPATIUM">
  <!-- Generated by scripts/generate-favicons.mjs from public/brand/mark-spatium.svg -->
  <defs>
    <style>
      .cls-1 { fill: url(#radial-gradient); }
      .base { fill: #040711; }
      @media (prefers-color-scheme: dark) { .base { fill: #ffffff; } }
    </style>
    ${gradient}
  </defs>
  ${accentPath}
  ${basePath.replace('<path ', '<path class="base" ')}
</svg>
`
fs.writeFileSync(path.join(root, 'public/favicon.svg'), svg)

// --- Raster icons ------------------------------------------------------------
/** White mark centred on the dark tile; `scale` = mark width relative to the tile. */
async function tile(size, scale, radius = 0) {
  const markWidth = Math.round(size * scale)
  const markPng = await sharp(MARK_ON_DARK, { density: 600 }).resize({ width: markWidth }).png().toBuffer()
  const meta = await sharp(markPng).metadata()
  const background = radius
    ? Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${radius}" fill="${TILE}"/></svg>`)
    : null
  const base = background
    ? sharp(background)
    : sharp({ create: { width: size, height: size, channels: 4, background: TILE } })
  return base
    .composite([{
      input: markPng,
      left: Math.round((size - markWidth) / 2),
      // Optical centring: the mark's mass sits low, so nudge it up slightly.
      top: Math.round((size - (meta.height ?? 0)) / 2 - size * 0.02),
    }])
    .png()
    .toBuffer()
}

fs.writeFileSync(path.join(root, 'public/apple-touch-icon.png'), await tile(180, 0.7))
fs.writeFileSync(path.join(root, 'public/icon-192.png'), await tile(192, 0.7))
// Maskable: keep the mark inside the 80% safe zone.
fs.writeFileSync(path.join(root, 'public/icon-512.png'), await tile(512, 0.6))

// PNG-in-ICO container (supported by every current browser).
const icoSizes = [16, 32, 48]
const images = await Promise.all(icoSizes.map((s) => tile(s, 0.8, Math.round(s * 0.18))))
const header = Buffer.alloc(6)
header.writeUInt16LE(0, 0)
header.writeUInt16LE(1, 2)
header.writeUInt16LE(images.length, 4)
let offset = 6 + 16 * images.length
const entries = images.map((img, i) => {
  const e = Buffer.alloc(16)
  e.writeUInt8(icoSizes[i], 0)
  e.writeUInt8(icoSizes[i], 1)
  e.writeUInt8(0, 2)
  e.writeUInt8(0, 3)
  e.writeUInt16LE(1, 4)
  e.writeUInt16LE(32, 6)
  e.writeUInt32LE(img.length, 8)
  e.writeUInt32LE(offset, 12)
  offset += img.length
  return e
})
fs.writeFileSync(path.join(root, 'src/app/favicon.ico'), Buffer.concat([header, ...entries, ...images]))

console.log('✓ favicon.svg, favicon.ico, apple-touch-icon.png, icon-192.png, icon-512.png generated')
